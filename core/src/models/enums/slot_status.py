from enum import Enum


class SlotStatus(str, Enum):
    """Состояние слота.

    - ``free``    — слот доступен для бронирования;
    - ``booked``  — слот занят активным бронированием;
    - ``blocked`` — слот недоступен из-за пересечения с активной записью
      (например, буфер после одной услуги накладывается на соседний слот).
    """

    FREE = "free"
    BOOKED = "booked"
    BLOCKED = "blocked"
