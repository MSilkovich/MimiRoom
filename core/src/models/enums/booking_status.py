from enum import Enum


class BookingStatus(str, Enum):
    """Статус бронирования.

    Слоты больше не материализуются, поэтому отдельного статуса слота нет.
    ``cancelled`` — единственный статус, при котором время записи снова
    доступно для новых броней; активные статусы учитываются при расчёте
    доступности и проверке пересечений.
    """

    PENDING = "pending"
    CONFIRMED = "confirmed"
    CANCELLED = "cancelled"
